import { test, expect } from "@playwright/test";
import { startEditor } from "./start-editor";

test("inline title saves, cancels and survives reload; file menu retains commands", async ({ page }) => {
  await startEditor(page);
  const title = page.getByRole('textbox', { name: 'Diagram title' });
  await title.fill('Renamed diagram');
  await title.press('Enter');
  await expect(page.locator('.save-status')).toHaveText('Saved locally');
  await page.reload();
  await page.getByRole('button', { name: 'Open Renamed diagram', exact: true }).click();
  await expect(title).toHaveValue('Renamed diagram');
  await title.fill('Discard me');
  await title.press('Escape');
  await expect(title).toHaveValue('Renamed diagram');
  await title.fill('   ');
  await title.press('Enter');
  await expect(title).toHaveValue('Renamed diagram');
  await title.fill('Saved on blur');
  await page.locator('.header-divider').click();
  await expect(page.locator('.save-status')).toHaveText('Saved locally');
  await expect(page.getByRole('button', { name: 'Rename diagram', exact: true })).toHaveCount(0);
  const menu = page.getByRole('button', { name: 'Diagram actions' });
  await menu.click();
  await expect(page.getByRole('button', { name: 'Export JSON', exact: true })).toBeVisible();
  await page.screenshot({ path: '/tmp/header-menu.png' });
  await page.keyboard.press('Escape');
  await expect(menu).toBeFocused();
  await page.locator('.component-copy strong', { hasText: 'Notes API' }).click();
  await menu.click();
  await page.keyboard.press('Tab');
  await expect(page.getByRole('button', { name: 'Diagrams', exact: true })).toBeFocused();
  await page.keyboard.press('Delete');
  await expect(page.locator('.component-card')).toHaveCount(3);
  await page.locator('.header-divider').click();
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await menu.click();
  await page.getByRole('button', { name: 'Delete diagram', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Delete this diagram?' })).toBeVisible();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(menu).toBeFocused();
  await menu.click();
  await page.getByRole('button', { name: 'New diagram', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 700 });
  await menu.click();
  await expect(page.getByRole('button', { name: 'Export JSON', exact: true })).toBeInViewport();
  await page.screenshot({ path: '/tmp/header-menu-mobile.png' });
});
